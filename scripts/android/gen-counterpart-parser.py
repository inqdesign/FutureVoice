#!/usr/bin/env python3
"""Lift CounterpartParser's plain parse prompt out of the Swift source into Kotlin.

The prompt is CONTENT, and retyped content drifts: the two platforms would file
the same spoken description of a friend into two different profiles. So it is
extracted, never copied by hand — the plain parse and the public-figure
lookup (`identifyPublicFigure`, used by `PublicFigureLookup.kt`).

    python3 scripts/android/gen-counterpart-parser.py [--check] [--ref <sha>]

Fails loudly on any interpolation other than `\\(nativeName)`.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/CounterpartParsePrompt.kt"
src = show("FutureVoice/Services/CounterpartParser.swift")
text = kotlin(literal_at(src, 'return """', src.index("private static func systemPrompt(nativeLanguage: String)")),
              {"nativeName": "nativeName"})
public = kotlin(literal_at(src, 'system: """', src.index("static func identifyPublicFigure(")),
                {"nativeName": "nativeName"})

emit(OUT, f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-counterpart-parser.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/CounterpartParser.swift (systemPrompt, identifyPublicFigure).

/**
 * Turns the learner's spoken description of someone they know into profile
 * fields, every one in the learner's NATIVE language — it is their own note
 * about their own friend.
 */
object CounterpartParsePrompt {{
    fun system(nativeName: String): String =
        {text}

    /** iOS `identifyPublicFigure`'s system prompt: WHO a public figure is. */
    fun publicFigure(nativeName: String): String =
        {public}
}}
''')
