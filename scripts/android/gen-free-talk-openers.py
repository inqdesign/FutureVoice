#!/usr/bin/env python3
"""Lift FreeTalkOpeners' bundled lines out of the Swift source.

Two pieces of CONTENT: the per-language INTRO line (the very first free talk,
before the fluent self has met the learner) and the per-language PICK-UP lines
every later free talk rotates through — hand-written since iOS 2026-10-13, so
the Gemini pool prompt this script used to lift is gone. Retyped, the two
platforms greet the same learner differently — and the intro line is the
first thing the product ever says.

    python3 scripts/android/gen-free-talk-openers.py [--check] [--ref <sha>]
"""
import pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, kt  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/FreeTalkOpenerContent.kt"
src = show("FutureVoice/Services/FreeTalkOpeners.swift")

STR = r'"((?:[^"\\]|\\.)*)"'


def table(name):
    m = re.search(rf'private static let {name}: \[String: String\] = \[(.*?)\n\s*\]', src, re.S)
    if not m: sys.exit(f"no table {name}")
    pairs = re.findall(r'"(\w+)":\s*' + STR, m.group(1))
    if not pairs: sys.exit(f"empty table {name}")
    return pairs


def list_table(name):
    m = re.search(rf'private static let {name}: \[String: \[String\]\] = \[(.*?)\n    \]', src, re.S)
    if not m: sys.exit(f"no table {name}")
    groups = re.findall(r'"(\w+)": \[(.*?)\n\s*\],', m.group(1), re.S)
    out = [(k, re.findall(STR, body)) for k, body in groups]
    if not out or any(len(v) < 1 for _, v in out): sys.exit(f"empty table {name}")
    return out


intro = table("introOpeners")
pick_up = list_table("pickUpLines")


def swift_unescape(v):
    """A Swift string literal's body as text (`\\u{202F}` included)."""
    v = re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), v)
    return re.sub(r'\\(["\\nt])', lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), v)


def kmap(pairs):
    return ",\n".join(f'        "{k}" to {kt(swift_unescape(v))}' for k, v in pairs)


def klists(groups):
    return ",\n".join(
        f'        "{k}" to listOf(\n'
        + ",\n".join(f"            {kt(swift_unescape(x))}" for x in lines)
        + "\n        )"
        for k, lines in groups)


emit(OUT, f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-free-talk-openers.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/FreeTalkOpeners.swift

/** Bundled greeting lines, lifted from the iOS source. */
object FreeTalkOpenerContent {{
    /** The very first free talk, before the fluent self has met the learner
     *  (`UserPersona.metAt == null`). It introduces ITSELF first. */
    val intro: Map<String, String> = mapOf(
{kmap(intro)}
    )

    /** How every later free talk picks up (iOS `pickUpLines`): glad they
     *  called, the floor handed to them, no guessed topic. Rotated; the
     *  first line is also what speaks while no pool exists yet. */
    val pickUp: Map<String, List<String>> = mapOf(
{klists(pick_up)}
    )
}}
''')
