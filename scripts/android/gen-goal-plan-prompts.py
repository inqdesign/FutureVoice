#!/usr/bin/env python3
"""Lift a goal plan's call notes out of the Swift source.

Byte for byte, from FutureVoice/Services/GoalPlan.swift (iOS 6aece49b),
`GoalPlan.Item.call(for:)`:
  - the mock run's note to the tutor (`.rehearse`), and how its questions
    are listed;
  - the day itself's warm-up note (`.theDay`).
The rest of that function (which call each item opens) is ported by hand in
GoalPlan.kt and PINNED here: the run fails the day its Swift changes.

    python3 scripts/android/gen-goal-plan-prompts.py [--check] [--ref <sha>]
"""
import pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, kt, unescape, func_body, pin  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/GoalPlanPrompts.kt"
src = show("FutureVoice/Services/GoalPlan.swift")

LIT = r'"((?:[^"\\]|\\.)*)"'

body = func_body(src, "call", src.index("func call(for goal: UpcomingGoal)"))


def case_body(name: str) -> str:
    i = body.index(f"case .{name}")
    j = body.find("case .", i + 1)
    return body[i:j if j >= 0 else len(body)]


# --- the mock run ------------------------------------------------------------
reh = case_body("rehearse")
m = re.search(r"blurb \+= " + LIT + r"\s*\+ " + LIT, reh)
if not m:
    sys.exit("the mock run's note changed shape")
mock_note = unescape(m.group(1)) + unescape(m.group(2))
m = re.search(r"if !qs\.isEmpty \{ blurb \+= " + LIT + r' \+ qs\.joined\(separator: ' + LIT + r"\) \}", reh)
if not m:
    sys.exit("the mock run's question list changed shape")
questions_head, questions_sep = unescape(m.group(1)), unescape(m.group(2))

# --- the day itself ----------------------------------------------------------
day = case_body("theDay")
m = re.search(r"blurb: goal\.drillBlurb \+ " + LIT + r"\s*\+ " + LIT, day)
if not m:
    sys.exit("the day's note changed shape")
day_note = unescape(m.group(1)) + unescape(m.group(2))

# --- hand-ported pieces, pinned ----------------------------------------------
pin({
    # Which call each item opens (GoalPlan.kt `Item.call`).
    "GoalPlan.Item.call": (body, "ada990287c4e"),
})

emit(OUT, f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-goal-plan-prompts.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/GoalPlan.swift (GoalPlan.Item.call).

object GoalPlanPrompts {{
    /** iOS `.rehearse`: what the mock run asks of the tutor, after the drill blurb. */
    const val MOCK_RUN = {kt(mock_note)}

    /** iOS `.rehearse`: the questions, when the page has worked them out. */
    const val MOCK_RUN_QUESTIONS = {kt(questions_head)}
    const val MOCK_RUN_SEPARATOR = {kt(questions_sep)}

    /** iOS `.theDay`: the warm-up on the day itself, after the drill blurb. */
    const val THE_DAY = {kt(day_note)}
}}
''')
