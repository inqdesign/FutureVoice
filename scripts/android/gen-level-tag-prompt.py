#!/usr/bin/env python3
"""Lift the level tagging prompt and the level map out of iOS at the pinned ref.

Byte for byte, from FutureVoice/Services/LevelTagger.swift (iOS 465331f6,
personal report step 3):
  - `LevelTagger.systemPrompt` (the probe-measured prompt);
  - its two line templates, `grammarLine` and `functionLine`;
  - `fixesHeader` and `fixLine`, the user message's corrections block.
And FutureVoice/Resources/LevelMap/level_map_<code>.json, copied as is into
the app's assets (`level_map/`), so the map the prompt is built from is the
map iOS ships.

    python3 scripts/android/gen-level-tag-prompt.py [--check] [--ref <sha>]
"""
import pathlib, re, subprocess, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin, kt  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/LevelTagPrompts.kt"
ASSETS = ROOT / "android/app/src/main/assets/level_map"
src = show("FutureVoice/Services/LevelTagger.swift")


def line_literal(anchor):
    """The one-line `"…"` literal right after `anchor`, as segments
    ('t', text) / ('i', expr) — the same shape `literal_at` returns."""
    i = src.index(anchor)
    o = src.index('"', i)
    k, segs, buf = o + 1, [], ""
    while src[k] != '"':
        c = src[k]
        if c == "\\":
            nxt = src[k + 1]
            if nxt == "(":
                depth, j = 1, k + 2
                while depth:
                    if src[j] == "(": depth += 1
                    elif src[j] == ")": depth -= 1
                    j += 1
                if buf: segs.append(("t", buf)); buf = ""
                segs.append(("i", src[k + 2:j - 1]))
                k = j
                continue
            buf += {"\"": "\"", "\\": "\\", "n": "\n", "t": "\t"}[nxt]
            k += 2
            continue
        buf += c
        k += 1
    if buf: segs.append(("t", buf))
    return segs


sp = src.index("static func systemPrompt(map: LevelMap, targetName: String)")
system = kotlin(literal_at(src, 'return """', sp), {
    "targetName": "targetName",
    "grammarLines": "grammarLines",
    "functionLines": "functionLines",
})
grammar_line = kotlin(line_literal("static func grammarLine(_ g: LevelMap.Grammar) -> String {"), {
    "g.id": "g.id", "g.name": "g.name", "g.counts": "g.counts",
    "g.example": "g.example", "g.error": "g.error",
})
function_line = kotlin(line_literal("static func functionLine(_ f: LevelMap.Function) -> String {"), {
    "f.id": "f.id", "f.name": "f.name", "f.counts": "f.counts",
})
fixes_header = kotlin(line_literal("static let fixesHeader ="), {})
fix_line = kotlin(line_literal("static func fixLine(was: String, now: String) -> String {"), {
    "was": "was", "now": "now",
})

# The joins systemPrompt builds its two lists with: one line per item.
body = src[sp:src.index('return """', sp)]
assert 'map.grammar.map(grammarLine).joined(separator: "\\n")' in body, "grammarLines join changed"
assert 'map.functions.map(functionLine).joined(separator: "\\n")' in body, "functionLines join changed"

emit(OUT, f'''package com.roro.futurevoice.talk

import com.roro.futurevoice.data.LevelMap

// GENERATED by scripts/android/gen-level-tag-prompt.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/LevelTagger.swift (systemPrompt, grammarLine,
// functionLine, fixesHeader, fixLine).

object LevelTagPrompts {{
    /** iOS `LevelTagger.grammarLine`. */
    fun grammarLine(g: LevelMap.Grammar): String =
        {grammar_line}

    /** iOS `LevelTagger.functionLine`. */
    fun functionLine(f: LevelMap.Function): String =
        {function_line}

    /** iOS `LevelTagger.systemPrompt`. */
    fun systemPrompt(map: LevelMap, targetName: String): String {{
        val grammarLines = map.grammar.joinToString("\\n") {{ grammarLine(it) }}
        val functionLines = map.functions.joinToString("\\n") {{ functionLine(it) }}
        return {system}
    }}

    /** iOS `LevelTagger.fixesHeader`. */
    val FIXES_HEADER: String =
        {fixes_header}

    /** iOS `LevelTagger.fixLine`. */
    fun fixLine(was: String, now: String): String =
        {fix_line}
}}
''')

# The maps themselves, one per language iOS ships.
names = subprocess.run(["git", "-C", str(ROOT), "ls-tree", "--name-only", REF,
                        "FutureVoice/Resources/LevelMap/"],
                       check=True, capture_output=True, text=True).stdout.split()
maps = [n for n in names if re.search(r"level_map_\w+\.json$", n)]
assert maps, "no level map at the ref"
for rel in maps:
    emit(ASSETS / pathlib.Path(rel).name, show(rel))
