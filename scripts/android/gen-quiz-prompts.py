#!/usr/bin/env python3
"""Lift the quick quiz's two prompts out of the iOS Swift source.

`QuickQuizStock.writeBatch` writes the written questions (grammar and the
level's expressions) and `QuickQuizStock.check` re-reads them blind, keeping
a question only when its answer alone fits. Both literals are read here with
Swift's own semantics and written into `data/QuickQuizPrompts.kt`; the code
around them (the user message, the parsing, the validation) is hand-ported in
`data/QuickQuizStock.kt`.

    python3 scripts/android/gen-quiz-prompts.py [--check] [--ref <sha>]
"""
import pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/data/QuickQuizPrompts.kt"
IND = "            "
src = show("FutureVoice/Services/QuickQuizStock.swift")


def lift(fn_anchor, lit_anchor, interp):
    if fn_anchor not in src:
        sys.exit(f"anchor not found: {fn_anchor!r}")
    return kotlin(literal_at(src, lit_anchor, src.index(fn_anchor)), interp, IND)


write = lift("static func writeBatch(appState: AppState)", 'let system = """', {
    "targetName": "targetName", "nativeName": "nativeName", "level": "level",
    "WeeklyTestEngine.blankMark": "WeeklyTestEngine.BLANK_MARK",
    'WordSplitter.spaced ? "5–12 words" : "8–25 characters"': '(if (spaced) "5–12 words" else "8–25 characters")',
    'spokenTopics.isEmpty ? "" : " (their recent topics: \\(spokenTopics.joined(separator: "; ")))"':
        '(if (spokenTopics.isEmpty()) "" else " (their recent topics: ${spokenTopics.joinToString("; ")})")',
    "batchPerKind": "QuickQuizStock.BATCH_PER_KIND",
})
check = lift("private static func check(_ questions: [Stored]", 'let system = """', {"targetName": "targetName"})

emit(OUT, f'''package com.roro.futurevoice.data

// GENERATED by scripts/android/gen-quiz-prompts.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/QuickQuizStock.swift (writeBatch's and check's
// system prompts), read with Swift's own literal semantics at that ref.

/** The quick quiz's prompt TEXT, byte for byte iOS's. */
object QuickQuizPrompts {{
    /** iOS `QuickQuizStock.writeBatch`'s system prompt. [spaced] is
     *  `WordSplitter.spaced` for the target language. */
    fun writeSystem(targetName: String, nativeName: String, level: String, spaced: Boolean,
                    spokenTopics: List<String>): String =
            {write}

    /** iOS `QuickQuizStock.check`'s system prompt. */
    fun checkSystem(targetName: String): String =
            {check}
}}
''')
