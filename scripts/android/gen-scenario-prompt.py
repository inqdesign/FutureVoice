#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Lift ScenarioCurriculumEngine's system prompt into the Android-only
`scenario-curriculum` edge function.

iOS writes a Watch scene client-side (`ScenarioCurriculumEngine`) and calls
`gemini` with purpose "scenario-curriculum" — it never calls this edge
function; Android does. Read from the Swift source at the pinned ref
(promptgen/IOS_REF), never retyped.

    python3 scripts/android/gen-scenario-prompt.py [--check] [--ref <sha>] [--fingerprints]

Writes `supabase/functions/scenario-curriculum/prompt.ts`. GENERATED: the
`systemPrompt` literal, `sceneTurnRange` / `sceneTurnStyle` /
`sceneMaxTokens`, `ConversationEngine.speechScale`'s six literals and
`CoachingLanguage.breathPunctuation`. HAND-PORTED and PINNED: `userMessage`
(the edge function's own, plus Android's counterpart block in
`CurriculumClient.counterpartLines`), `isBuiltin`, `CommonGround.block`'s
call site, `generate`'s model / ceiling / purpose.
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import (ROOT, REF, show, emit, literal_at, plain, func_body, pin, ts,  # noqa: E402
                    ts_template)

OUT = ROOT / "supabase/functions/scenario-curriculum/prompt.ts"
ENGINE = show("FutureVoice/Services/ScenarioCurriculumEngine.swift")
CONV = show("FutureVoice/Services/ConversationEngine.swift")
COACHING = show("FutureVoice/Services/CoachingLanguage.swift")

pin({
    "userMessage": (func_body(ENGINE, "userMessage"), "1d736265f29a"),
    "isBuiltin": (func_body(ENGINE, "isBuiltin"), "dfe080434b85"),
    "generate": (func_body(ENGINE, "generate"), "fae0ac88109e"),
    "systemPrompt (wrapper)": (func_body(ENGINE, "systemPrompt").split('return """')[0], "8eced5f9a8c6"),
})

turn_range = re.search(r'static let sceneTurnRange = "([^"]+)"', ENGINE)
max_tokens = re.search(r"static let sceneMaxTokens = (\d+)", ENGINE)
if not turn_range or not max_tokens:
    sys.exit("sceneTurnRange / sceneMaxTokens not found")
turn_style = plain(literal_at(ENGINE, "static let sceneTurnStyle"))

# speechScale: three branches, each `vocabulary: """…""", structure: """…"""`.
scale = func_body(CONV, "speechScale")
cases = re.findall(r"case (\.[a-c][12](?:, \.[a-c][12])*):", scale)
if cases != [".a1, .a2", ".b1, .b2", ".c1, .c2"]:
    sys.exit(f"speechScale's branches changed: {cases}")
bands = {}
for name, anchor in (("low", "case .a1, .a2"), ("mid", "case .b1, .b2"), ("high", "case .c1, .c2")):
    at = scale.index(anchor)
    voc = plain(literal_at(scale, "vocabulary:", at))
    st = plain(literal_at(scale, "structure:", at))
    bands[name] = (voc, st)

breath = plain(literal_at(COACHING, "static let breathPunctuation"))
system = ts(literal_at(ENGINE, 'return """', ENGINE.index("static func systemPrompt(")), {
    "languageName": "${languageName}",
    "proficiency.rawValue.uppercased()": "${prof}",
    "CoachingLanguage.breathPunctuation": "${BREATH_PUNCTUATION}",
    "sceneTurnRange": "${SCENE_TURN_RANGE}",
    "sceneTurnStyle": "${SCENE_TURN_STYLE}",
    "band.vocabulary": "${band.vocabulary}",
    "band.structure": "${band.structure}",
})
J = lambda s: json.dumps(s, ensure_ascii=False)

emit(OUT, f'''// GENERATED by `scripts/android/gen-scenario-prompt.py` from the iOS source at
// `{REF}` (ScenarioCurriculumEngine.systemPrompt, sceneTurnRange/Style/
// MaxTokens, ConversationEngine.speechScale, CoachingLanguage.breathPunctuation).
// Do not edit by hand — re-run the generator.

import {{ englishName }} from "../session-summary/prompt.ts"

export const SCENE_TURN_RANGE = {J(turn_range.group(1))}
export const SCENE_TURN_STYLE = {J(turn_style)}
/** One ceiling: the payload is the same size for every learner. */
export const SCENE_MAX_TOKENS = {max_tokens.group(1)}
export const BREATH_PUNCTUATION = {J(breath)}

/** `ConversationEngine.speechScale(for:)` — the ONE definition of a band. */
export function speechScale(prof: string): {{ vocabulary: string; structure: string }} {{
  switch (prof.toLowerCase()) {{
    case "a1": case "a2": return {{ vocabulary: {J(bands["low"][0])}, structure: {J(bands["low"][1])} }}
    case "c1": case "c2": return {{ vocabulary: {J(bands["high"][0])}, structure: {J(bands["high"][1])} }}
    default: return {{ vocabulary: {J(bands["mid"][0])}, structure: {J(bands["mid"][1])} }}
  }}
}}

/** `ScenarioCurriculumEngine.systemPrompt`, verbatim. `prof` is upper-case. */
export function systemPrompt(targetLanguage: string, prof: string): string {{
  const languageName = englishName(targetLanguage)
  const band = speechScale(prof)
  return `{system}`
}}
''')
