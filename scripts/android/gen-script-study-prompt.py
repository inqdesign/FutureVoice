#!/usr/bin/env python3
"""Lift the Speech script Study prompt (iOS `ScriptStudyEngine.generate`) out
of the Swift source, and pin the hand-ported rules around it.

Study mode marks 7–8 expressions / grammar patterns / words IN a script and
writes a native-language note under each paragraph — one call, purpose
"script-study". The prompt is extracted, never retyped. The code that is
ported by hand (span verification, the cache key, the voiceover's price, keys,
lines and assembly) is fingerprinted here: the day iOS changes any of it, this
run fails and names what to re-port.

    python3 scripts/android/gen-script-study-prompt.py [--check] [--ref <sha>]

Read at its own pin (promptgen/LOCAL_PINS) — the shared IOS_REF predates it.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin, func_body, pin  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/ScriptStudyPrompt.kt"
study = show("FutureVoice/Services/Speech/ScriptStudy.swift")
voiceover = show("FutureVoice/Services/Speech/ScriptVoiceover.swift")

gen_at = study.index("private static func generate(")
system = kotlin(literal_at(study, 'let system = """', gen_at), {
    "level.rawValue.uppercased()": "level",
    "target": "target",
    "nativeName": "nativeName",
    "CoachingLanguage.contract(target: script.language, native: native)": "contract",
}, "            ")

# The user message is one line of Swift; held by fingerprint with the rest.
USER_LINE = 'let user = "SCRIPT (\\(paragraphs.count) paragraphs):\\n\\(numbered)"'
if USER_LINE not in study:
    sys.exit("gen-script-study-prompt.py: the user message changed at iOS — re-port ScriptStudyPrompt.user")

pin({
    "ScriptStudy.generate": (func_body(study, "generate"), "b204873c7aaa"),
    "ScriptStudy.locate": (func_body(study, "locate"), "8738e0518b25"),
    "ScriptStudy.occurrences": (func_body(study, "occurrences"), "a43791fd36fc"),
    "ScriptStudy.onBoundary": (func_body(study, "onBoundary"), "6ef473c7d617"),
    "ScriptStudy.paragraphs": (func_body(study, "paragraphs"), "f3b279d1aad9"),
    "ScriptStudy.cacheKey": (func_body(study, "cacheKey"), "39330416e108"),
    "ScriptVoiceover.chargeMinutes": (func_body(voiceover, "chargeMinutes"), "0c9242178081"),
    "ScriptVoiceover.cappedChargeMinutes": (func_body(voiceover, "cappedChargeMinutes"), "ecc023cb7594"),
    "ScriptVoiceover.remainingMinutes": (func_body(voiceover, "remainingMinutes"), "e483623b1e84"),
    "ScriptVoiceover.chargeKey": (func_body(voiceover, "chargeKey"), "a33fe3abc0f7"),
    "ScriptVoiceover.fileKey": (func_body(voiceover, "fileKey"), "63222c7e1f69"),
    "ScriptVoiceover.lines": (func_body(voiceover, "lines"), "d9124b2ddcaa"),
    "ScriptVoiceoverCenter.make": (func_body(voiceover, "make"), "056fd8f5b3ea"),
    "ScriptVoiceoverAudio.join": (func_body(voiceover, "join"), "b1066336957e"),
})

emit(OUT, f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-script-study-prompt.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/Speech/ScriptStudy.swift (ScriptStudyEngine.generate).

/**
 * The Speech script Study prompt: highlights copied verbatim from the script
 * (MATERIAL, target language) and one native-language note per paragraph
 * (coaching). The spans are verified in code ([com.roro.futurevoice.data.ScriptStudy.locate]).
 */
object ScriptStudyPrompt {{
    fun system(level: String, target: String, nativeName: String, contract: String): String {{
        return {system}
    }}

    fun user(paragraphs: List<String>): String {{
        val numbered = paragraphs.mapIndexed {{ i, p -> "${{i + 1}}. $p" }}.joinToString("\\n")
        return "SCRIPT (${{paragraphs.size}} paragraphs):\\n$numbered"
    }}
}}
''')
