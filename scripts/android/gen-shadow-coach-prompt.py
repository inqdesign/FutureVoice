#!/usr/bin/env python3
"""Lift ShadowEngine's coach prompt (system + user message) out of the Swift source.

The three bullets a learner reads between shadow attempts are written from
these instructions, and the user message is the EVIDENCE they are anchored
to (the diff, the duration ratio, the off-beat words). Retyped, the two
platforms would coach the same take differently — and the lines a retype
drops are the load-bearing ones ("treat the diff as ground truth", "you have
no pitch data, so never claim to hear intonation", the field-by-field
language rule). So it is extracted, never copied by hand.

    python3 scripts/android/gen-shadow-coach-prompt.py [--check] [--ref <sha>]

Fails loudly on any interpolation it does not know how to map.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/ShadowCoachPrompt.kt"
src = show("FutureVoice/Services/ShadowEngine.swift")

system = kotlin(literal_at(src, 'return """', src.index("static func systemPrompt(targetLanguage: String,")), {
    "LanguageCatalog.englishName(targetLanguage)": "targetName",
    "nativeName": "nativeName",
}, "            ")
user = kotlin(literal_at(src, 'return """', src.index("static func userMessage(")), {
    "targetText": "targetText",
    'learnerText.isEmpty ? "(empty)" : learnerText': "learnerShown",
    "targetDurationMs": "targetDurationMs",
    "learnerDurationMs": "learnerDurationMs",
    "ratio": "ratio",
    "renderDiffForPrompt(diffSteps)": "diff",
    "renderRhythmForPrompt(rhythm)": "rhythmText",
}, "            ")

emit(OUT, f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-shadow-coach-prompt.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/ShadowEngine.swift (systemPrompt, userMessage).

import com.roro.futurevoice.data.LanguageCatalog

/**
 * The shadow coach: three native-language bullets (pronunciation · pacing ·
 * try this) anchored to the deterministic diff and the measured beat. The
 * numeric score is computed in code and never asked of the model.
 */
object ShadowCoachPrompt {{
    fun system(targetLanguage: String, nativeLanguage: String): String {{
        val targetName = LanguageCatalog.englishName(targetLanguage)
        val nativeName = LanguageCatalog.englishName(nativeLanguage)
        return {system}
    }}

    fun userMessage(
        targetText: String,
        learnerText: String,
        targetDurationMs: Int,
        learnerDurationMs: Int,
        diffSteps: List<ShadowScore.DiffStep>,
        rhythm: ShadowScore.RhythmAnalysis?,
    ): String {{
        val ratio = if (targetDurationMs > 0)
            String.format(java.util.Locale.US, "%.2f", learnerDurationMs.toDouble() / targetDurationMs)
        else "n/a"
        val learnerShown = if (learnerText.isEmpty()) "(empty)" else learnerText
        val diff = ShadowScore.renderDiffForPrompt(diffSteps)
        val rhythmText = ShadowScore.renderRhythmForPrompt(rhythm)
        return {user}
    }}
}}
''')
