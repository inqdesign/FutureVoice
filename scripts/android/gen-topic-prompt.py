#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Lift TopicEngine.categorize's prompt into the Android-only `topic-engine`
edge function, and the composer's icon palette (the list that prompt makes
the model choose from) into Android.

iOS builds the prompt client-side and calls `gemini`; Android calls
`topic-engine`. Read from the Swift source at the pinned ref
(promptgen/IOS_REF), never retyped.

    python3 scripts/android/gen-topic-prompt.py [--check] [--ref <sha>] [--fingerprints]

Writes `supabase/functions/topic-engine/prompt.ts` (the system literal and the
user line) and `android/.../net/ScenarioIconPalette.kt`
(`ScenarioComposerSheet.iconPalette`). The call's model, token ceiling and
purpose are pinned: the run fails if `categorize` changes anywhere outside its
literal.
"""
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, func_body, pin, ts  # noqa: E402

OUT = ROOT / "supabase/functions/topic-engine/prompt.ts"
KT = ROOT / "android/app/src/main/java/com/roro/futurevoice/net/ScenarioIconPalette.kt"
ENGINE = show("FutureVoice/Services/TopicEngine.swift")
COMPOSER = show("FutureVoice/Views/ScenarioComposerSheet.swift")

body = func_body(ENGINE, "categorize")
close = body.index('\n        """') + len('\n        """')
pin({"categorize (outside the literal)": (body[close:], "0eed15462758")})

system = ts(literal_at(ENGINE, 'let system = """', ENGINE.index("static func categorize(")), {
    'existing.isEmpty ? "(none)" : existing.joined(separator: ", ")':
        '${existing.length === 0 ? "(none)" : existing.join(", ")}',
    'iconOptions.joined(separator: ", ")': '${iconOptions.join(", ")}',
})
user = re.search(r'content: "scenario: \\\(text\)"', body)
if not user:
    sys.exit("categorize's user line changed")

pal = re.search(r"static let iconPalette = \[(.*?)\]", COMPOSER, re.S)
if not pal:
    sys.exit("ScenarioComposerSheet.iconPalette not found")
icons = re.findall(r'"([^"]+)"', pal.group(1))
if not icons:
    sys.exit("iconPalette is empty")

emit(OUT, f'''// GENERATED by `scripts/android/gen-topic-prompt.py` from the iOS source at
// `{REF}` (TopicEngine.categorize). Do not edit by hand — re-run the generator.

/** `TopicEngine.categorize`'s system prompt, verbatim. */
export function categorizePrompt(existing: string[], iconOptions: string[]): string {{
  return `{system}`
}}

/** `TopicEngine.categorize`'s user message. */
export function categorizeUserLine(text: string): string {{
  return `scenario: ${{text}}`
}}
''')

items = ",\n".join(f'        "{i}"' for i in icons)
emit(KT, f'''package com.roro.futurevoice.net

// GENERATED by scripts/android/gen-topic-prompt.py --ref {REF} — do not edit.
// Source: FutureVoice/Views/ScenarioComposerSheet.swift (iconPalette).

/** The SF Symbol names the categorizer may choose from, in iOS's order —
 *  they are interpolated into the prompt, so the list IS prompt text.
 *  Drawn through `ui.brand.Symbols`. */
object ScenarioIconPalette {{
    val ICONS: List<String> = listOf(
{items},
    )
}}
''')
