#!/usr/bin/env python3
"""Lift the tutor chat's agent prompt out of the Swift source at the pinned iOS ref.

Byte for byte (iOS 57ba9c6f, the text `TutorAgentPromptDumpTests` dumps):
  - `TutorChat.rules(native:target:)` (FutureVoice/Services/TutorBot.swift)
    — who the tutor is and how it answers, with its Korean line;
  - `TutorAgent.manual` and `TutorAgent.protocolBlock`
    (FutureVoice/Services/TutorAgent.swift) — the app, and the chat's JSON
    protocol, with `TutorTools.catalog` (the lookups) inside it.
The learner's context and the lookups' answers are built by hand in
TutorBot.kt / TutorAgent.kt and PINNED here: the run fails the day their
Swift changes.

    python3 scripts/android/gen-tutor-agent-prompts.py [--check] [--ref <sha>]
"""
import pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin, plain, kt, unescape, func_body, pin  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/TutorAgentPrompts.kt"
bot = show("FutureVoice/Services/TutorBot.swift")
agent = show("FutureVoice/Services/TutorAgent.swift")

LIT = r'"((?:[^"\\]|\\.)*)"'

catalog = plain(literal_at(agent, 'static let catalog = """'))
manual = plain(literal_at(agent, 'static let manual = """'))
protocol = kotlin(literal_at(agent, 'static let protocolBlock = """'), {"TutorTools.catalog": "CATALOG"})

rf = bot.index("static func rules(native nativeCode: String, target targetCode: String)")
korean = re.search(r'let korean = nativeCode == "ko"\s*\? ' + LIT + r' : ""', bot[rf:]).group(1)
# The tutor speaks the target language (iOS 183419f0): the translation rule is
# one of two plain literals, the first carrying \(native) and \(korean).
tr = re.search(r'let translationRule = translated\s*\? ' + LIT + r'\s*: ' + LIT, bot[rf:])
tr_yes, tr_no = tr.group(1), tr.group(2)
tr_parts = re.split(r'\\\((native|korean)\)', tr_yes)
translation_rule = " + ".join(p if n % 2 else kt(unescape(p)) for n, p in enumerate(tr_parts) if n % 2 or p)
rules = kotlin(literal_at(bot, 'return """', rf), {
    "target": "target", "native": "native", "translationRule": "translationRule",
    "TutorAgent.manual": "MANUAL", "TutorAgent.protocolBlock": "protocolBlock",
})

# --- hand-ported pieces, pinned ----------------------------------------------
tools = {name: func_body(agent, name, agent.index("enum TutorTools"))
         for name in ("progressLine", "run", "talks", "talk", "search", "mistakes", "notebook",
                      "cards", "progress", "goals", "routine", "scenarios", "kind")}
pinned = {"TutorChat.context": (func_body(bot, "context", bot.index("final class TutorChat")), "PIN_CONTEXT"),
          "TutorChat.ask": (func_body(bot, "ask", bot.index("final class TutorChat")), "PIN_ASK"),
          "TutorAction.title": (agent[agent.index("var title: String {"):agent.index("/// Kept only if what it points at")], "PIN_TITLE"),
          "TutorAction.isValid": (func_body(agent, "isValid", agent.index("struct TutorAction")), "PIN_VALID")}
for name, body in tools.items():
    pinned[f"TutorTools.{name}"] = (body, f"PIN_{name.upper()}")
FINGERPRINTS = {
    "TutorChat.context": "3cff0fa71a5b",
    "TutorChat.ask": "fd4435973577",
    "TutorAction.title": "afa73f17ac0d",
    "TutorAction.isValid": "71bb28ef1d01",
    "TutorTools.progressLine": "05daf3e31ad4",
    "TutorTools.run": "121e26343355",
    "TutorTools.talks": "a8c31f4c7d6e",
    "TutorTools.talk": "01baf97ff72a",
    "TutorTools.search": "bedd8f1e8f11",
    "TutorTools.mistakes": "fd62f7ae6a1e",
    "TutorTools.notebook": "b1899acb3a8d",
    "TutorTools.cards": "083e4fcd96be",
    "TutorTools.progress": "01c157f2ef60",
    "TutorTools.goals": "52d9050f28e9",
    "TutorTools.routine": "f1d7fc60f643",
    "TutorTools.scenarios": "4d6eccc417d8",
    "TutorTools.kind": "18f54ba88e07",
}
pin({k: (v[0], FINGERPRINTS.get(k, v[1])) for k, v in pinned.items()})

emit(OUT, f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-tutor-agent-prompts.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/TutorBot.swift (TutorChat.rules) and
// FutureVoice/Services/TutorAgent.swift (TutorAgent.manual, protocolBlock,
// TutorTools.catalog).

object TutorAgentPrompts {{
    /** iOS `TutorTools.catalog`: the lookups the model may ask for. */
    const val CATALOG: String = {kt(catalog)}

    /** iOS `TutorAgent.manual`: what each part of the app is for. */
    const val MANUAL: String = {kt(manual)}

    /** iOS `TutorAgent.protocolBlock`: the chat's JSON protocol. */
    val protocolBlock: String =
        {protocol}

    /** iOS `TutorChat.rules(native:target:)`'s Korean line. */
    fun korean(nativeCode: String): String = if (nativeCode == "ko") {kt(unescape(korean))} else ""

    /** iOS `TutorChat.rules(native:target:)`'s translation rule: the reply's
     *  own words in the learner's language, unless the two are one language. */
    fun translationRule(translated: Boolean, native: String, korean: String): String =
        if (translated) {translation_rule} else {kt(unescape(tr_no))}

    /** iOS `TutorChat.rules(native:target:)`: everything but the learner. */
    fun rules(native: String, target: String, translationRule: String): String =
        {rules}
}}
''')
