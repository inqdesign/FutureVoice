#!/usr/bin/env python3
"""Lift tutor mode's prompt text out of the Swift source at a ref.

Two pieces of `ConversationEngine.swift` (iOS `b3a6d30f` + `234e77cf`):
  - `tutorBlock(targetLanguage:languageName:)` — the TUTOR MODE block
    appended LAST to the conversation prompt when the learner turned it on;
  - the STRICT line it swaps: "Never correct the user mid-conversation…"
    becomes "Correct the user only as TUTOR MODE below says.".
The block splices in the correction prompt's ASR guards, which Android
already carries byte for byte in `CorrectionOnlyPrompt` (generated from the
same Swift functions), so they are called, not copied.

    python3 scripts/android/gen-tutor-block.py --ref 234e77cf
"""
import argparse, json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/TutorPrompt.kt"

ap = argparse.ArgumentParser()
ap.add_argument("--ref", default="234e77cf")
args = ap.parse_args()

src = subprocess.run(["git", "-C", str(ROOT), "show", f"{args.ref}:FutureVoice/Services/ConversationEngine.swift"],
                     check=True, capture_output=True, text=True).stdout


def unescape(s):
    """A Swift string literal's body (no interpolation) as text."""
    out, k = "", 0
    while k < len(s):
        if s[k] == "\\":
            out += {"\"": "\"", "\\": "\\", "n": "\n", "t": "\t"}[s[k + 1]]
            k += 2
        else:
            out += s[k]; k += 1
    return out


def literal_after(anchor):
    """The Swift multiline literal that opens on the first `\"\"\"` after
    `anchor`, as segments ('t', text) / ('i', expr)."""
    i = src.find(anchor)
    if i < 0: sys.exit(f"anchor not found: {anchor!r}")
    o = src.find('"""', i)
    body_start = src.find("\n", o) + 1
    close = re.compile(r'\n([ \t]*)"""').search(src, body_start - 1)
    raw = src[body_start:close.start() + 1]
    indent = close.group(1)
    out = []
    for ln in raw.split("\n")[:-1]:
        if ln.strip() == "": out.append("")
        elif ln.startswith(indent): out.append(ln[len(indent):])
        else: sys.exit(f"bad indent: {ln!r}")
    text = ""
    for n, ln in enumerate(out):
        last = n == len(out) - 1
        if ln.endswith("\\") and not ln.endswith("\\\\"):
            text += ln[:-1]
        else:
            text += ln + ("" if last else "\n")
    segs, buf, k = [], "", 0
    while k < len(text):
        c = text[k]
        if c == "\\":
            nxt = text[k + 1]
            if nxt == "(":
                depth, j, in_str = 1, k + 2, False
                while depth:
                    ch = text[j]
                    if ch == "\\" and in_str: j += 2; continue
                    if ch == '"': in_str = not in_str
                    elif not in_str and ch == "(": depth += 1
                    elif not in_str and ch == ")": depth -= 1
                    j += 1
                if buf: segs.append(("t", buf)); buf = ""
                segs.append(("i", text[k + 2:j - 1]))
                k = j
                continue
            buf += {"\"": "\"", "\\": "\\", "n": "\n", "t": "\t"}[nxt]
            k += 2
            continue
        buf += c
        k += 1
    if buf: segs.append(("t", buf))
    return segs


def kt(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


KO_ONLY = re.compile(r'^LanguageCatalog\.base\(targetLanguage\) == "ko" \? "((?:[^"\\]|\\.)*)" : ""$')
interp = {
    "languageName": "languageName",
    "scriptGuard(targetLanguage)": "CorrectionOnlyPrompt.scriptGuard(targetLanguage)",
    "spacingGuard(targetLanguage)": "CorrectionOnlyPrompt.spacingGuard(targetLanguage)",
    "registerGuard(targetLanguage)": "CorrectionOnlyPrompt.registerGuard(targetLanguage)",
}
parts = []
for kind, v in literal_after("static func tutorBlock(targetLanguage: String, languageName: String)"):
    if kind == "t":
        parts.append(kt(v))
    elif v in interp:
        parts.append(interp[v])
    elif (m := KO_ONLY.match(v)):
        parts.append(f'(if (targetLanguage.substringBefore(\'-\') == "ko") {kt(unescape(m.group(1)))} else "")')
    else:
        sys.exit(f"unmapped interpolation: {v}")
block = " +\n            ".join(parts)

m = re.search(r'- \\\(tutor \? "((?:[^"\\]|\\.)*)" : "((?:[^"\\]|\\.)*)"\)', src)
if not m: sys.exit("the STRICT tutor/never-correct line changed shape")
tutor_line, never_line = unescape(m.group(1)), unescape(m.group(2))

OUT.write_text(f'''package com.roro.futurevoice.talk

// GENERATED by scripts/android/gen-tutor-block.py --ref {args.ref} — do not edit.
// Source: FutureVoice/Services/ConversationEngine.swift (tutorBlock, and the
// STRICT line it swaps).

/** iOS `ConversationEngine.tutorBlock` + the correction line it replaces. */
object TutorPrompt {{
    /** The STRICT line with tutor mode on. */
    const val CORRECT_ONLY_AS_TUTOR = {kt(tutor_line)}

    /** The STRICT line with tutor mode off — every other prompt's. */
    const val NEVER_CORRECT = {kt(never_line)}

    /** Appended LAST to the conversation prompt, only when tutor mode is on. */
    fun block(targetLanguage: String, languageName: String): String =
        {block}
}}
''')
print(f"wrote {OUT.relative_to(ROOT)}")
