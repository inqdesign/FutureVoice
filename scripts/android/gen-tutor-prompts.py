#!/usr/bin/env python3
"""Lift tutor mode's lesson prompts out of the Swift source at the pinned iOS ref.

Byte for byte, from FutureVoice/Services/TutorLesson.swift (iOS af3c7ffe …
bd242766):
  - `TutorPlanner.plan`'s system prompt, and `levelLadder`'s bands;
  - `TutorNext.read`'s system prompt;
  - `TutorJudge.read`'s system prompt and user message;
  - `TutorFinalCheck.read`'s system prompt and user message.
The one-line messages and the app's nudges (ConversationView) are ported by
hand in TutorLesson.kt, next to the logic that sends them.

    python3 scripts/android/gen-tutor-prompts.py [--check] [--ref <sha>]
"""
import pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, kotlin, plain, kt  # noqa: E402

OUT = ROOT / "android/app/src/main/java/com/roro/futurevoice/talk/TutorPrompts.kt"
src = show("FutureVoice/Services/TutorLesson.swift")

pl = src.index("static func plan(request: String")
planner = kotlin(literal_at(src, 'let system = """', pl), {
    "target": "target",
    "native": "native",
    "level.rawValue.uppercased()": "level.code.uppercase()",
    "levelLadder(level)": "levelLadder(level)",
    'about.isEmpty ? "" : "\\nWhat is known about them: \\(about). Context only."':
        '(if (about.isEmpty()) "" else "\\nWhat is known about them: $about. Context only.")',
})

nx = src.index("enum TutorNext {")
next_offer = kotlin(literal_at(src, 'let offer = suggested.map { """', nx), {"$0": "suggested"})
next_ = kotlin(literal_at(src, 'let system = """', nx), {"lesson": "lesson", "offer": "offer"})

lad = src.index("static func levelLadder(_ level: CEFRLevel)")
bands = {}
pos = lad
for case in ("a1", "a2", "b1", "b2", "c1, .c2"):
    at = src.index(f"case .{case}:", pos)
    bands[case] = kotlin(literal_at(src, 'band = """', at),
                         {"level.rawValue.uppercased()": "level.code.uppercase()"}, "                ")
    pos = at + 1
beyond = plain(literal_at(src, 'let beyond = [.a1, .a2].contains(level) ? "" : """', lad))
ladder_head = 'WHAT THIS LEVEL PRACTICES — the challenges must fit this, not a level below:\\n'
assert 'return "' + ladder_head + '" + band + beyond' in src[lad:], "levelLadder's return line changed"

jd = src.index("enum TutorJudge {")
judge = kotlin(literal_at(src, 'let system = """', jd), {"target": "target"})
judge_content = kotlin(literal_at(src, 'let content = """', jd), {
    "challenge.task": "task", "challenge.example": "example",
    "askedWith": "askedWith", "line": "line",
    'ownLanguage ? "\\n(They said this in their own language, not in \\(target).)" : ""':
        '(if (ownLanguage) "\\n(They said this in their own language, not in $target.)" else "")',
})

fc = src.index("enum TutorFinalCheck {")
check = kotlin(literal_at(src, 'let system = """', fc), {"target": "target", "lesson.titleTarget": "titleTarget"})
check_content = kotlin(literal_at(src, 'let content = """', fc), {
    "parts": "parts", "askedWith": "askedWith", "line": "line",
})

emit(OUT, f'''package com.roro.futurevoice.talk

import com.roro.futurevoice.data.CefrLevel

// GENERATED by scripts/android/gen-tutor-prompts.py --ref {REF} — do not edit.
// Source: FutureVoice/Services/TutorLesson.swift (TutorPlanner, TutorNext,
// TutorJudge, TutorFinalCheck).

object TutorPrompts {{
    /** iOS `TutorPlanner.plan`'s system prompt; [about] is "occupation · city" or "". */
    fun plannerSystem(target: String, native: String, level: CefrLevel, about: String): String =
        {planner}

    /** iOS `TutorPlanner.levelLadder`. */
    fun levelLadder(level: CefrLevel): String {{
        val band = when (level) {{
            CefrLevel.A1 ->
                {bands["a1"]}
            CefrLevel.A2 ->
                {bands["a2"]}
            CefrLevel.B1 ->
                {bands["b1"]}
            CefrLevel.B2 ->
                {bands["b2"]}
            CefrLevel.C1, CefrLevel.C2 ->
                {bands["c1, .c2"]}
        }}
        val beyond = if (level == CefrLevel.A1 || level == CefrLevel.A2) "" else
            {kt(beyond)}
        return "{ladder_head}" + band + beyond
    }}

    /** iOS `TutorNext.read`'s system prompt; [suggested] is the next topic
     *  on their curriculum, when there is one. */
    fun nextSystem(lesson: String, suggested: String? = null): String {{
        val offer = if (suggested == null) "" else
            {next_offer}
        return {next_}
    }}

    /** iOS `TutorJudge.read`'s system prompt. */
    fun judgeSystem(target: String): String =
        {judge}

    /** iOS `TutorJudge.read`'s user message. */
    fun judgeContent(task: String, example: String, askedWith: String, line: String,
                     target: String = "", ownLanguage: Boolean = false): String =
        {judge_content}

    /** iOS `TutorFinalCheck.read`'s system prompt. */
    fun finalCheckSystem(target: String, titleTarget: String): String =
        {check}

    /** iOS `TutorFinalCheck.read`'s user message; [parts] are the numbered tasks. */
    fun finalCheckContent(parts: String, askedWith: String, line: String): String =
        {check_content}
}}
''')
