#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Lift VoicemailEngine's system prompt into the Android-only
`voicemail-script` edge function.

iOS builds the daily call's script client-side (`VoicemailEngine.systemPrompt`)
and calls `gemini`; Android calls `voicemail-script`, which builds the same
prompt server-side. The first copy was retyped and drifted (the TIME block,
the WHEN THEY HEAR IT block on a no-ring script, where the breath rule sits,
an extra "you gave up for the day" line iOS never had). So the text is read
out of the Swift source at the pinned ref (promptgen/IOS_REF), never retyped.

    python3 scripts/android/gen-voicemail-prompt.py [--check] [--ref <sha>] [--fingerprints]

Writes `supabase/functions/voicemail-script/prompt.ts`. GENERATED: the whole
`systemPrompt` literal, `CoachingLanguage.breathPunctuation` / `.selfWarmth`,
`baseScriptCharacters`. HAND-PORTED and PINNED (the run fails when the Swift
changes): the grounding list, `whenHeard`, `PromptClock.partOfDay`,
`calendarDays`, `dayLine`, the call's model/tokens/user line, and the
client's `sanitize` / `maxScriptCharacters` (Android `VoicemailClient`).
"""
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / "promptgen"))
from iosref import ROOT, REF, show, emit, literal_at, plain, func_body, pin, ts  # noqa: E402

OUT = ROOT / "supabase/functions/voicemail-script/prompt.ts"
ENGINE = show("FutureVoice/Services/VoicemailEngine.swift")
CLOCK = show("FutureVoice/Services/PromptClock.swift")
COACHING = show("FutureVoice/Services/CoachingLanguage.swift")

sp = func_body(ENGINE, "systemPrompt")
max_chars = re.search(r"static var maxScriptCharacters: Int \{(.*?)\n    \}", ENGINE, re.S)
base = re.search(r"static let baseScriptCharacters = (\d+)", ENGINE)
if not max_chars or not base:
    sys.exit("maxScriptCharacters / baseScriptCharacters not found")

pin({
    "systemPrompt(grounding)": (sp[:sp.index('return """')], "8fcf1968324a"),
    "whenHeard": (func_body(ENGINE, "whenHeard"), "182c094c9a4c"),
    "writeScript": (func_body(ENGINE, "writeScript"), "f35ec2b51b5d"),
    "sanitize": (func_body(ENGINE, "sanitize"), "a8ac3ae9834e"),
    "maxScriptCharacters": (max_chars.group(1), "1f8ab19e25ae"),
    "PromptClock.partOfDay": (func_body(CLOCK, "partOfDay"), "b006f6f83623"),
    "PromptClock.calendarDays": (func_body(CLOCK, "calendarDays"), "a5c975e37610"),
    "PromptClock.dayLine": (func_body(CLOCK, "dayLine"), "44240a1245c6"),
})

body = ts(literal_at(ENGINE, 'return """', ENGINE.index("static func systemPrompt(")), {
    "groundingBlock": "${groundingBlock}",
    "whenHeard(c.ringDates, calendar: calendar)": "${whenHeard(c.ringDates, offset)}",
    "targetName": "${targetName}",
    "maxScriptCharacters": "${maxScriptCharacters}",
    "c.proficiency.rawValue.uppercased()": "${c.proficiency.toUpperCase()}",
    "CoachingLanguage.breathPunctuation": "${BREATH_PUNCTUATION}",
    "CoachingLanguage.selfWarmth": "${SELF_WARMTH}",
    "name": "${name}",
    "LanguageCatalog.englishName(c.nativeLanguage)": "${englishName(c.nativeLanguage)}",
})
breath = plain(literal_at(COACHING, "static let breathPunctuation"))
warmth = plain(literal_at(COACHING, "static let selfWarmth"))
J = lambda s: json.dumps(s, ensure_ascii=False)

emit(OUT, f'''// GENERATED by `scripts/android/gen-voicemail-prompt.py` from the iOS source at
// `{REF}` (VoicemailEngine.systemPrompt, CoachingLanguage.breathPunctuation /
// .selfWarmth). Do not edit by hand — re-run the generator.
//
// HAND-PORTED (pinned by the generator, which fails if the Swift changes):
// the grounding list, `whenHeard`, `partOfDay`.

import {{ calendarDays, dayLine, englishName }} from "../session-summary/prompt.ts"

export const BASE_SCRIPT_CHARACTERS = {base.group(1)}
export const BREATH_PUNCTUATION = {J(breath)}
export const SELF_WARMTH = {J(warmth)}

/** `VoicemailEngine.Context` — the facts the client sends. */
export interface VoicemailContext {{
  targetLanguage: string
  nativeLanguage: string
  /** CEFR code, any case ("b1"). */
  proficiency: string
  personaName?: string
  lastTopic?: string
  lastPhrases: string[]
  lastTalkAt?: Date
  /** An older Android build's own day count, used only without lastTalkAt. */
  legacyDaysSinceLastTalk?: number
  dueCount: number
  lastOutcome?: "answered" | "declined" | "missed"
  consecutiveUnanswered: number
  ringDates: Date[]
  /** The learner's zone, in minutes east of UTC (iOS reads `Calendar.current`). */
  utcOffsetMinutes: number
  /** `VoicemailEngine.maxScriptCharacters` at the learner's speech speed. */
  maxScriptCharacters: number
}}

/** `PromptClock.partOfDay(hour:)`. */
export function partOfDay(hour: number): string {{
  if (hour >= 5 && hour < 12) return "morning"
  if (hour >= 12 && hour < 17) return "afternoon"
  if (hour >= 17 && hour < 22) return "evening"
  return "night"
}}

/** `VoicemailEngine.whenHeard` — the ring(s), in the learner's zone. */
export function whenHeard(ringDates: Date[], offset: number): string {{
  const dates = ringDates.length === 0 ? [new Date()]
    : [...ringDates].sort((a, b) => a.getTime() - b.getTime())
  const local = (d: Date) => new Date(d.getTime() + offset * 60_000)
  const hhmm = (d: Date) => {{
    const l = local(d)
    return `${{String(l.getUTCHours()).padStart(2, "0")}}:${{String(l.getUTCMinutes()).padStart(2, "0")}}`
  }}
  const day = dayLine(dates[0], offset)
  if (dates.length === 1) {{
    const part = partOfDay(local(dates[0]).getUTCHours())
    return `It rings on ${{day}}, at ${{hhmm(dates[0])}} — ${{part}}.`
  }}
  const times = dates.map(hhmm).join(", ")
  return `It rings on ${{day}}, at ${{times}} — the same message each time until they pick up, so you cannot know which part of the day they hear it in.`
}}

/** `VoicemailEngine.systemPrompt`, verbatim. */
export function systemPrompt(c: VoicemailContext): string {{
  const offset = c.utcOffsetMinutes
  const targetName = englishName(c.targetLanguage)
  const name = c.personaName ? c.personaName : "the learner"
  const maxScriptCharacters = c.maxScriptCharacters

  const grounding: string[] = []
  if (c.lastTopic) grounding.push(`Their last talk was about: ${{c.lastTopic}}`)
  if (c.lastPhrases.length > 0) {{
    grounding.push("Phrases that came up in it: "
      + c.lastPhrases.slice(0, 4).map((p) => `"${{p}}"`).join(", "))
  }}
  const ringDay = c.ringDates.length === 0 ? new Date()
    : new Date(Math.min(...c.ringDates.map((d) => d.getTime())))
  const days = c.lastTalkAt ? calendarDays(c.lastTalkAt, ringDay, offset) : c.legacyDaysSinceLastTalk
  if (days !== undefined) {{
    grounding.push(days === 0 ? "They already had a talk earlier today."
      : days === 1 ? "Their last talk was yesterday."
      : `It has been ${{days}} days since their last talk.`)
  }}
  if (c.dueCount > 0) grounding.push(`${{c.dueCount}} review cards are waiting.`)
  switch (c.lastOutcome) {{
    case "answered": grounding.push("Last time you called, they picked up and you talked."); break
    case "declined": grounding.push("Last time you called, they said they couldn't talk right then."); break
    case "missed": grounding.push("Last time you called, they never picked up."); break
  }}
  if (c.consecutiveUnanswered >= 2) {{
    grounding.push(`You haven't actually got hold of them in ${{c.consecutiveUnanswered}} calls.`)
  }}
  const groundingBlock = grounding.length === 0
    ? "You have no history with them yet — this is the first call."
    : grounding.map((g) => `- ${{g}}`).join("\\n")

  return `{body}`
}}
''')
