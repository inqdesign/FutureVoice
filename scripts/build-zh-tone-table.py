#!/usr/bin/env python3
"""The pronunciation call's Chinese tone table (PronunciationContrast).

One line per syllable: every single-character HSK word with that syllable,
by tone, the most basic first. Built from the app's own wordlist so both
apps swap the same characters. Writes the Swift and the Kotlin constant.

    python3 scripts/build-zh-tone-table.py [android-repo]
"""
import sys, os
TONE = {}
for base, marks in (("a", "āáǎà"), ("e", "ēéěè"), ("i", "īíǐì"), ("o", "ōóǒò"), ("u", "ūúǔù"), ("ü", "ǖǘǚǜ")):
    for t, m in enumerate(marks, 1): TONE[m] = (base, t)
def parse(py):
    tone, out = 5, ""
    for ch in py:
        if ch in TONE: out += TONE[ch][0]; tone = TONE[ch][1]
        else: out += ch
    return out, tone
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
entries = []   # (char, syllable, tone), in list order
seen = set()
for line in open(os.path.join(root, "FutureVoice/Resources/cefr_words_zh.tsv"), encoding="utf-8"):
    f = line.rstrip("\n").split("\t")
    if len(f) < 3 or len(f[0]) != 1 or f[0] in seen: continue
    py = f[2].split("/")[0].split(",")[0].strip().lower()
    if not py or " " in py: continue
    s, t = parse(py)
    if t == 5: continue
    seen.add(f[0]); entries.append((f[0], s, t))
data = ";".join(f"{c}{s}{t}" for c, s, t in entries)
header = "Generated by scripts/build-zh-tone-table.py from cefr_words_zh.tsv (HSK 3.0, pinyin from CC-CEDICT). Do not edit."
swift = f'''// {header}

/// Single-character HSK words as "字syllableN;…", N the tone 1–4.
enum ChineseToneTable {{
    static let data = "{data}"
}}
'''
kotlin = f'''package com.roro.futurevoice.talk

// {header}

/** Single-character HSK words as "字syllableN;…", N the tone 1–4. */
object ChineseToneTable {{
    const val DATA = "{data}"
}}
'''
open(os.path.join(root, "FutureVoice/Services/ChineseToneTable.swift"), "w", encoding="utf-8").write(swift)
android = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(root), "FutureVoice-android")
open(os.path.join(android, "android/app/src/main/java/com/roro/futurevoice/talk/ChineseToneTable.kt"), "w", encoding="utf-8").write(kotlin)
print(len(entries), "characters")
