import json,sys
mp=json.load(open(sys.argv[1]))
rows="\n".join(f'  "{k}": ["{v["lang"]}", "{v["copy"]}"],  // {v["name"]}' for k,v in sorted(mp.items()))
head='''// A library voice speaking a language that isn't its own (2026-10-23).
//
// A person in Find people speaks in a Cartesia LIBRARY voice picked by their
// native language (ProfileVoices.swift), and keeps it in every language
// (2026-10-12). Read in another language, a library voice carries its own
// accent — a Korean voice's English sounded wrong (founder, in Watch), and
// Cartesia refuses an accent on a voice we don't own. So each library voice
// has an OWNED copy, cloned once from ~12 s of the voice in its own language
// (scripts/voice-copies/), and a line in any other language is spoken by the
// copy with NO accent named — the founder's pick by ear over the copy told
// general-american (Desktop/beta audio/library-voice-accent-2026-10-23).
// In its own language the library voice speaks as before.
//
// GENERATED by scripts/voice-copies/make.py. Mirror: gateway/src/voice-copies.ts.

/** library voice → [its own language, the owned copy] */
const COPIES: Record<string, [string, string]> = {
'''
tail='''}

/** The voice to send for a line in `language` when `voiceId` is a library
 *  voice outside its own language: the copy, marked `original-<lang>` so no
 *  default accent is added. Null for anything else. */
export function foreignVoice(voiceId: string, language: string): string | null {
  const entry = COPIES[voiceId.toLowerCase()]
  if (!entry) return null
  const lang = language.toLowerCase().split("-")[0]
  return entry[0] === lang ? null : `${entry[1]}:original-${lang}`
}
'''
open(sys.argv[2],"w").write(head+rows+"\n"+tail)
open(sys.argv[3],"w").write(head.replace("Mirror: gateway/src/voice-copies.ts","Mirror of supabase/functions/_shared/voice-copies.ts")+rows+"\n"+tail)
