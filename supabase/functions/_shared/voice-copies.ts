/** The voice to send for a line in `language` when `voiceId` is a library
 *  voice outside its own language: the copy, marked `original-<lang>` so no
 *  default accent is added. Null for anything else. */
export function foreignVoice(voiceId: string, language: string): string | null {
  const entry = COPIES[voiceId.toLowerCase()]
  if (!entry) return null
  const lang = language.toLowerCase().split("-")[0]
  return entry[0] === lang ? null : `${entry[1]}:original-${lang}`
}
